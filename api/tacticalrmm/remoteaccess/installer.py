"""
Installers generated by the TRMM server (used by the TRMM Desktop app and by
the quick support "install permanent access" flow):

- Windows: Tactical RMM agent (installer.ps1) and, optionally, the TRMM Desktop
  host in the same script. The remote access part always runs, even if the
  tactical/mesh agent fails.
- Linux: same idea in bash (the tactical agent needs the code signing token).
"""

import asyncio
import datetime as dt
from pathlib import Path

from django.conf import settings

from .files import GOARCH, api_url, download_url, enroll_ticket, host_file, sha256
from .models import RemoteAccessConfig
from .scripts import LINUX_BIN, WIN_EXE, host_script, server_config


class InstallerError(ValueError):
    pass


def _installer_token(hours: int, created: list | None = None) -> str:
    from knox.models import AuthToken

    from accounts.models import User

    installer_user = User.objects.filter(is_installer_user=True).first()
    if installer_user is None:
        raise InstallerError("No installer user found")
    instance, token = AuthToken.objects.create(user=installer_user, expiry=dt.timedelta(hours=hours))
    if created is not None:
        created.append(instance)
    return token


def _clean(data) -> dict:
    """validated installer options (values go into generated scripts)"""
    import re

    goarch = str(data.get("goarch", "amd64"))
    if goarch not in ("amd64", "386", "arm64", "arm"):
        raise InstallerError("Invalid architecture")
    agenttype = str(data.get("agenttype", "workstation"))
    if agenttype not in ("workstation", "server"):
        raise InstallerError("Invalid agent type")
    try:
        expires = min(max(int(data.get("expires", 24)), 1), 24 * 30)
        flags = {k: 1 if int(data.get(k, 0)) else 0 for k in ("power", "rdp", "ping")}
    except (TypeError, ValueError):
        raise InstallerError("Invalid installer options")
    # servers never sleep/hibernate (same rule as tacticalrmm.utils.install_power_flag)
    if agenttype == "server":
        flags["power"] = 1
    api = data.get("api")
    if api is not None:
        api = str(api).strip().rstrip("/")
        if not re.fullmatch(r"https?://[A-Za-z0-9.\-]+(:[0-9]{1,5})?(/[A-Za-z0-9._~/\-]*)?", api):
            raise InstallerError("Invalid api url")
    return {"goarch": goarch, "agenttype": agenttype, "expires": expires, "api": api, **flags}


def _ra_config() -> str:
    cfg = RemoteAccessConfig.load()
    try:
        return server_config(cfg.id_server, cfg.relay_server, cfg.public_key)
    except ValueError as e:
        raise InstallerError(str(e))


def build_windows(request, site, data, remote_access: bool = True, created: list | None = None) -> str:
    """data: agenttype, goarch, expires (hours), power, rdp, ping, api (optional)"""
    from agents.utils import get_agent_url
    from core.utils import token_is_valid

    data = _clean(data)
    goarch = data["goarch"]
    host = None
    ra_config = ""
    if remote_access:
        host = host_file("windows", "x64")
        if host is None:
            raise InstallerError("TRMM Desktop installer not found on the server")
        ra_config = _ra_config()

    # same value the dashboard sends to /agents/installer/ (full api url)
    api = str(data.get("api") or api_url(request))
    version = settings.LATEST_AGENT_VER
    codesign_token, _ = token_is_valid()
    token = _installer_token(data["expires"], created)

    trmm = Path(settings.BASE_DIR / "core" / "installer.ps1").read_text()
    for key, value in {
        # same name as agents/views.py install_agent (with .exe)
        "innosetupchange": f"tacticalagent-v{version}-windows-{goarch}.exe",
        "clientchange": str(site.client_id),
        "sitechange": str(site.pk),
        "apichange": api,
        "atypechange": data["agenttype"],
        "powerchange": str(data["power"]),
        "rdpchange": str(data["rdp"]),
        "pingchange": str(data["ping"]),
        "downloadchange": get_agent_url(goarch=goarch, plat="windows", token=codesign_token),
        "tokenchange": token,
    }.items():
        trmm = trmm.replace(key, value)
    if not remote_access:
        return trmm

    api_base = api_url(request)
    host_part = host_script(
        plat="windows",
        password="$($raPassword)",
        download_url=download_url(api_base, "windows", GOARCH.get(goarch, "x64")),
        sha256=sha256(host),
        install=True,
        config=ra_config,
    ).replace("'$($raPassword)'", "$raPassword")

    script = COMBINED_PS1
    for key, value in {
        "__TRMM_SCRIPT__": trmm.replace("'@", "' @"),
        "__HOST_SCRIPT__": host_part,
        "__RA_EXE__": WIN_EXE,
        "__API__": api_base,
        "__TOKEN__": token,
        "__SITE__": str(site.pk),
        "__TICKET__": enroll_ticket(site.pk, data["expires"]),
    }.items():
        script = script.replace(key, value)
    return script


def build_linux(request, site, data) -> str:
    """Linux: tactical agent (when the code signing token is valid) + remote access."""
    from agents.utils import get_agent_url
    from core.utils import get_core_settings, get_mesh_device_id, get_mesh_ws_url, token_is_valid
    from tacticalrmm.constants import MeshAgentIdent

    data = _clean(data)
    goarch = data["goarch"]
    arch = GOARCH.get(goarch, "x64")
    host = host_file("linux", arch)
    if host is None:
        raise InstallerError(f"TRMM Desktop package for linux/{arch} not found on the server")
    ra_config = _ra_config()
    token = _installer_token(data["expires"])
    api = str(data.get("api") or api_url(request))
    api_base = api_url(request)

    trmm = 'echo "Tactical agent for Linux needs the code signing token: skipped"; exit 1'
    codesign_token, is_valid = token_is_valid()
    if is_valid:
        try:
            arch_id = {
                "amd64": MeshAgentIdent.LINUX64,
                "386": MeshAgentIdent.LINUX32,
                "arm64": MeshAgentIdent.LINUX_ARM_64,
                "arm": MeshAgentIdent.LINUX_ARM_HF,
            }.get(goarch, "not_found")
            core = get_core_settings()
            mesh_id = asyncio.run(get_mesh_device_id(get_mesh_ws_url(), core.mesh_device_group))
            trmm = Path(settings.LINUX_AGENT_SCRIPT).read_text()
            for key, value in {
                "agentDLChange": get_agent_url(goarch=goarch, plat="linux", token=codesign_token),
                "meshDLChange": f"{core.mesh_site}/meshagents?id={mesh_id}&installflags=2&meshinstall={arch_id}",
                "clientIDChange": str(site.client_id),
                "siteIDChange": str(site.pk),
                "agentTypeChange": data["agenttype"],
                "tokenChange": token,
                "apiURLChange": api,
            }.items():
                trmm = trmm.replace(key, value)
        except Exception as e:  # mesh offline etc: still install remote access
            reason = "".join(c for c in str(e)[:200] if c.isalnum() or c in " .,:-_")
            trmm = f"echo 'Tactical agent script unavailable: {reason}'; exit 1"

    host_part = host_script(
        plat="linux",
        password="__RA_PASSWORD__",
        download_url=download_url(api_base, "linux", arch),
        sha256=sha256(host),
        install=True,
        config=ra_config,
    ).replace("'__RA_PASSWORD__'", '"$RA_PASSWORD"')

    script = COMBINED_SH
    for key, value in {
        "__TRMM_SCRIPT__": trmm,
        "__HOST_SCRIPT__": host_part,
        "__RA_BIN__": LINUX_BIN,
        "__API__": api_base,
        "__TOKEN__": token,
        "__SITE__": str(site.pk),
        "__TICKET__": enroll_ticket(site.pk, data["expires"]),
    }.items():
        script = script.replace(key, value)
    return script


COMBINED_PS1 = r"""# Tactical RMM + remote access (TRMM Desktop) installer.
# The remote access part always runs, even if the tactical/mesh agent fails.
# Run as administrator:  powershell -ExecutionPolicy Bypass -File trmm-install-remoteaccess.ps1

# 1) Tactical RMM agent (MeshCentral + Tactical). Runs in a child process so
#    an error or "exit" in it doesn't stop the remote access part.
$trmmScript = @'
__TRMM_SCRIPT__
'@
# folder only SYSTEM/Administrators can write: the script runs elevated
$work = Join-Path $env:SystemRoot ('Temp\trmm-install-' + [guid]::NewGuid().ToString('N'))
New-Item -ItemType Directory -Force $work | Out-Null
& icacls.exe $work /inheritance:r /grant:r '*S-1-5-18:(OI)(CI)F' '*S-1-5-32-544:(OI)(CI)F' | Out-Null
$trmmFile = Join-Path $work 'trmm-agent-install.ps1'
Set-Content -Path $trmmFile -Value $trmmScript -Encoding UTF8
$agentExit = -1
try {
    $p = Start-Process powershell.exe -ArgumentList "-NoProfile -ExecutionPolicy Bypass -File `"$trmmFile`"" -Wait -PassThru
    $agentExit = $p.ExitCode
} catch { Write-Warning "Tactical agent install failed: $($_.Exception.Message)" }
Remove-Item $work -Recurse -Force -ErrorAction SilentlyContinue

# 2) Remote access (always)
$chars = [char[]]'ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz23456789'
$rng = [Security.Cryptography.RandomNumberGenerator]::Create()
$bytes = New-Object byte[] 20
$rng.GetBytes($bytes)
$raPassword = -join ($bytes | ForEach-Object { $chars[$_ % $chars.Length] })
$hostOutput = & {
__HOST_SCRIPT__
} | Out-String
Write-Output $hostOutput
if ($hostOutput -match 'TRMMRA-ID:(\S+)') {
    $remoteId = $Matches[1]
    $agentId = (Get-ItemProperty 'HKLM:\SOFTWARE\TacticalRMM' -ErrorAction SilentlyContinue).AgentID
    $body = @{
        remote_id = $remoteId
        password  = $raPassword
        hostname  = $env:COMPUTERNAME
        os        = (Get-CimInstance Win32_OperatingSystem).Caption
        site      = '__SITE__'
        ticket    = '__TICKET__'
        agent_id  = $agentId
    } | ConvertTo-Json
    try {
        [Net.ServicePointManager]::SecurityProtocol = [Net.SecurityProtocolType]::Tls12
        $resp = Invoke-RestMethod -Method Post -Uri '__API__/remoteaccess/enroll/' -Body $body -ContentType 'application/json' -Headers @{ Authorization = 'Token __TOKEN__' }
        Write-Output "Remote access registered (id $remoteId)."
        # session recording: upload url + token of this computer
        if ($resp.record_url) {
            $recWork = Join-Path $env:SystemRoot ('Temp	rmm-rec-' + [guid]::NewGuid().ToString('N'))
            New-Item -ItemType Directory -Force $recWork | Out-Null
            & icacls.exe $recWork /inheritance:r /grant:r '*S-1-5-18:(OI)(CI)F' '*S-1-5-32-544:(OI)(CI)F' | Out-Null
            $recFile = Join-Path $recWork 'rec.json'
            (@{ url = [string]$resp.record_url; token = [string]$resp.record_token } | ConvertTo-Json -Compress) | Set-Content -Path $recFile -NoNewline -Encoding ASCII
            & '__RA_EXE__' --record-config $recFile | Out-Null
            Remove-Item $recWork -Recurse -Force -ErrorAction SilentlyContinue
        }
    } catch {
        Write-Warning "Remote access installed (id $remoteId) but could not be registered: $($_.Exception.Message)"
    }
} else {
    Write-Warning 'Remote access could not be installed.'
}
if ($agentExit -ne 0) { Write-Warning "Tactical agent installer exit code: $agentExit" }
"""


COMBINED_SH = r"""#!/usr/bin/env bash
# Tactical RMM + remote access (TRMM Desktop) installer for Linux (Debian/Ubuntu).
# The remote access part always runs, even if the tactical/mesh agent fails.
# Run as root:  sudo bash trmm-install-remoteaccess.sh
if [ "$(id -u)" -ne 0 ]; then echo "run as root (sudo)"; exit 1; fi

# 1) Tactical RMM agent, in a child shell (its errors/exit don't stop us)
TRMM_FILE=$(mktemp)
cat > "$TRMM_FILE" <<'TRMM_AGENT_EOF'
__TRMM_SCRIPT__
TRMM_AGENT_EOF
bash "$TRMM_FILE"
AGENT_EXIT=$?
rm -f "$TRMM_FILE"

# 2) Remote access (always)
RA_PASSWORD=$(tr -dc 'ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz23456789' </dev/urandom | head -c 20)
HOST_OUT=$(
__HOST_SCRIPT__
)
echo "$HOST_OUT"
REMOTE_ID=$(echo "$HOST_OUT" | sed -n 's/^TRMMRA-ID:\(\S*\).*/\1/p' | head -1)
if [ -n "$REMOTE_ID" ]; then
    AGENT_ID=$(grep -o '"agentid" *: *"[^"]*"' /etc/tacticalagent 2>/dev/null | sed 's/.*"\([^"]*\)"$/\1/')
    OS_NAME=$( . /etc/os-release 2>/dev/null; echo "${PRETTY_NAME:-Linux}")
    # json-safe values (drop quotes, backslashes and control chars)
    js() { printf '%s' "$1" | tr -d '"\\\000-\037'; }
    BODY=$(printf '{"remote_id":"%s","password":"%s","hostname":"%s","os":"%s","site":"%s","ticket":"%s","agent_id":"%s"}' \
        "$(js "$REMOTE_ID")" "$RA_PASSWORD" "$(js "$(hostname)")" "$(js "$OS_NAME")" "__SITE__" "__TICKET__" "$(js "$AGENT_ID")")
    if RESP=$(curl -fsS -X POST -H 'Content-Type: application/json' -H 'Authorization: Token __TOKEN__' \
        -d "$BODY" '__API__/remoteaccess/enroll/'); then
        echo "Remote access registered (id $REMOTE_ID)."
        # session recording: upload url + token of this computer
        REC_URL=$(printf '%s' "$RESP" | sed -n 's/.*"record_url" *: *"\([^"]*\)".*/\1/p')
        REC_TOKEN=$(printf '%s' "$RESP" | sed -n 's/.*"record_token" *: *"\([^"]*\)".*/\1/p')
        if [ -n "$REC_URL" ] && [ -n "$REC_TOKEN" ]; then
            RECF=$(mktemp)
            chmod 600 "$RECF"
            printf '{"url":"%s","token":"%s"}' "$REC_URL" "$REC_TOKEN" > "$RECF"
            '__RA_BIN__' --record-config "$RECF" >/dev/null 2>&1
            rm -f "$RECF"
        fi
    else
        echo "WARNING: remote access installed (id $REMOTE_ID) but could not be registered."
    fi
else
    echo "WARNING: remote access could not be installed."
fi
[ "$AGENT_EXIT" -ne 0 ] && echo "WARNING: tactical agent installer exit code: $AGENT_EXIT"
exit 0
"""
